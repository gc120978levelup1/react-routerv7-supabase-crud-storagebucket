export function AppSidebar({ ...props }: React.ComponentProps<typeof Sidebar>) {
  const [user1, setUser1] = useState({
    name: "shadcn",
    email: "m@example.com",
    avatar: "/avatars/shadcn.jpg",
  });

  useEffect(() => {
    void (async () => {
      const { supabase } = createClientSPA();
      const {
        data: { user },
        error: userError,
      } = await supabase.auth.getUser();
      if (userError) {
        console.error(userError.message);
        return;
      }
      if (!user) {
        return;
      }
      const path = `${user.id}/avatar`;
      const { data } = supabase.storage.from("images").getPublicUrl(path);
      console.log("garry error data url app sidebar",data.publicUrl)
      setUser1((prev) => ({
        name:  user.id,
        email: user.email ?? prev.email,
        avatar: data.publicUrl,
      }));
    })();
  }, []);

  return (
    <Sidebar collapsible="offcanvas" {...props}>
      <SidebarHeader>
        <SidebarMenu>
          <SidebarMenuItem>
            <SidebarMenuButton
              className="data-[slot=sidebar-menu-button]:p-1.5!"
              render={<a href="#" />}
            >
              <CommandIcon className="size-5!" />
              <span className="text-base font-semibold">Acme Inc.</span>
            </SidebarMenuButton>
          </SidebarMenuItem>
        </SidebarMenu>
      </SidebarHeader>
      <SidebarContent>
        <NavMain items={data1.navMain} />
        <NavDocuments items={data1.documents} />
        <NavSecondary items={data1.navSecondary} className="mt-auto" />
      </SidebarContent>
      <SidebarFooter>
        <NavUser user={user1} />
      </SidebarFooter>
    </Sidebar>
  );
}
